-- Companies whose own hiring pages are checked every day (Greenhouse, Lever, Ashby, Workable, SmartRecruiters).
create table if not exists jh_companies (
  ats text not null check (ats in ('greenhouse','lever','ashby','workable','smartrecruiters')),
  slug text not null,
  name text not null,
  added_by text not null default 'you',   -- starter | auto (found on a job site) | you
  active boolean not null default true,
  added_at timestamptz default now(),
  primary key (ats, slug)
);
alter table jh_companies enable row level security;
drop policy if exists jh_companies_owner on jh_companies;
create policy jh_companies_owner on jh_companies for all to authenticated using (jh_is_owner()) with check (jh_is_owner());

